_COMPILED = [(t, re.compile(t.pattern, re.IGNORECASE)) for t in VAGUE_TERMS]


def find_vague_words(text: str) -> list[dict]:
    """Находит «опасные слова» (ISO 29148 п. 5.2.7).

    Возвращает список словарей: word, category, hint, line (номер строки с 1),
    context (строка документа, обрезанная до 200 символов). Результат — подсказка
    для LLM-экспертов, а не окончательное замечание.
    """
    hits: list[dict] = []
    seen: set[tuple[int, str]] = set()
    for line_no, line in enumerate(text.splitlines(), start=1):
        stripped = line.strip()
        if not stripped or stripped.startswith("```"):
            continue
        for term, rx in _COMPILED:
            for m in rx.finditer(line):
                word = m.group(0)
                key = (line_no, word.lower())
                if key in seen:
                    continue
                seen.add(key)
                hits.append(
                    {
                        "word": word,
                        "category": term.category,
                        "hint": term.hint,
                        "line": line_no,
                        "context": stripped[:200],
                    }
                )
    return hits


def format_criteria(criteria: tuple[Criterion, ...]) -> str:
    return "\n".join(f"- **{c.name}** — {c.question}" for c in criteria)


def format_vague_hits(hits: list[dict], limit: int = 40) -> str:
    if not hits:
        return "(код не нашёл опасных слов)"
    lines = [
        f"- «{h['word']}» ({h['category']}; {h['hint']}) — строка {h['line']}: {h['context']}"
        for h in hits[:limit]
    ]
    if len(hits) > limit:
        lines.append(f"- … и ещё {len(hits) - limit}")
    return "\n".join(lines)
